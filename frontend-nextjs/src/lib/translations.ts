export type LangCode = keyof typeof TRANSLATIONS;
export type TranslationKey = keyof typeof TRANSLATIONS['en'];

// Language metadata
export const LANGUAGES: { code: LangCode; label: string; flag: string; browserCodes: string[] }[] = [
  { code: 'en', label: 'English',    flag: '🇺🇸', browserCodes: ['en', 'en-US', 'en-GB', 'en-AU'] },
  { code: 'vi', label: 'Tiếng Việt', flag: '🇻🇳', browserCodes: ['vi', 'vi-VN'] },
  { code: 'ko', label: '한국어',      flag: '🇰🇷', browserCodes: ['ko', 'ko-KR'] },
  { code: 'ja', label: '日本語',      flag: '🇯🇵', browserCodes: ['ja', 'ja-JP'] },
];

// Detect browser language → return supported LangCode
export function detectBrowserLanguage(): LangCode {
  if (typeof window === 'undefined') return 'en';
  const stored = localStorage.getItem('artlab-lang') as LangCode | null;
  if (stored && LANGUAGES.find(l => l.code === stored)) return stored;
  const nav = navigator.language || (navigator as any).userLanguage || 'en';
  const match = LANGUAGES.find(l => l.browserCodes.some(bc => nav.toLowerCase().startsWith(bc.toLowerCase())));
  return match?.code ?? 'en';
}

// Fallback: if key not in target lang, use English
export function getTranslation(lang: LangCode, key: TranslationKey): string {
  const t = TRANSLATIONS[lang] as Record<string, string>;
  return t?.[key] ?? TRANSLATIONS['en'][key];
}
